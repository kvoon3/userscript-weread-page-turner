/* eslint-disable antfu/no-top-level-await */
/**
 * Copies shared/weread-wheel.js into the MV3 extension and rebuilds index.js
 * (Greasy Fork needs a single self-contained userscript file).
 */
import fs from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const root = path.dirname(fileURLToPath(import.meta.url))
const sharedPath = path.join(root, 'shared', 'weread-wheel.js')
const extensionPath = path.join(root, 'extension', 'weread-wheel.js')
const packagePath = path.join(root, 'package.json')
const indexPath = path.join(root, 'index.js')

const shared = await fs.readFile(sharedPath, 'utf8')
await fs.writeFile(extensionPath, shared, 'utf8')

const { version } = JSON.parse(await fs.readFile(packagePath, 'utf8'))

const sharedBody = shared
  .replace(/^[\s\S]*?^'use strict'\s*\n/m, '')
  .trimEnd()
  .split('\n')
  .map(line => (line.length ? `  ${line}` : line))
  .join('\n')

const userscript = `// ==UserScript==
// @name         WeRead Page Turner
// @namespace    https://kvoonme.netlify.app/
// @version      ${version}
// @description  Better WeRead web page turning experience
// @author       Kevin Kwong
// @homepageURL  https://github.com/kvoon3/userscript-weread-page-turner
// @supportURL   https://github.com/kvoon3/userscript-weread-page-turner
// @match        https://weread.qq.com/web/reader/**
// @icon         https://www.google.com/s2/favicons?sz=64&domain=weread.qq.com
// @grant        none
// @run-at       document-body
// @license      MIT
// @downloadURL https://update.greasyfork.org/scripts/520296/WeRead%20Page%20Turner.user.js
// @updateURL https://update.greasyfork.org/scripts/520296/WeRead%20Page%20Turner.meta.js
// ==/UserScript==

/**
 * Generated by sync-shared.js from shared/weread-wheel.js — edit the shared file, then run: node sync-shared.js
 */
(function () {
  'use strict'

${sharedBody}

  installWereadPageTurner()
})()
`

await fs.writeFile(indexPath, `${userscript.trimEnd()}\n`, 'utf8')
process.stdout.write('Synced shared/weread-wheel.js → extension/weread-wheel.js and index.js\n')
