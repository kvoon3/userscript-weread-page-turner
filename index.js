/**
 * Generated by sync-shared.js from shared/weread-wheel.js — edit the shared file, then run: node sync-shared.js
 */
(function () {
  'use strict'

  function installWereadPageTurner(doc, win) {
    doc = doc || document
    win = win || window

    const WHEEL_THRESHOLD = 40
    const COOLDOWN_MS = 280

    /** Known overlays / panels that steal scroll when visible (verified + DOM-backed). */
    const OVERLAY_SELECTORS = [
      '.wr_mask_Show',
      '.login_dialog_container',
      '.wr_dialog_container',
      '.readerCatalog',
      '.readerNotePanel',
      '.readerAIChatPanel',
      '.reader-font-control-panel-wrapper',
      '.font-panel-content',
      '.reviews_panel',
      '.top_reviews_panel',
      '.search_panel',
      '.reader_float_panel_container',
      '.reader_common_dialog',
      '.wr_dialog_mask',
    ]

    const CATALOG_SELECTOR = '.readerCatalog'

    let cooldownUntil = 0
    let deltaCarry = 0

    function isElementVisible(el) {
      if (!el || !(el instanceof Element))
        return false

      const style = win.getComputedStyle(el)
      if (style.display === 'none' || style.visibility === 'hidden')
        return false
      if (Number.parseFloat(style.opacity) === 0)
        return false

      const rect = el.getBoundingClientRect()
      // Off-screen .wr_mask (left:-9999px) and zero-box hidden dialogs.
      if (rect.width <= 0 || rect.height <= 0)
        return false
      if (rect.right <= 0 || rect.bottom <= 0)
        return false
      if (rect.left >= win.innerWidth || rect.top >= win.innerHeight)
        return false

      return true
    }

    function isScrollableElement(el) {
      if (!(el instanceof Element))
        return false

      // Perfect Scrollbar marks overflow even when overflow is hidden.
      if (el.classList.contains('ps--active-y') || el.classList.contains('ps--active-x'))
        return true

      const style = win.getComputedStyle(el)
      const oy = style.overflowY
      const ox = style.overflowX
      const yScrollable = (oy === 'auto' || oy === 'scroll' || oy === 'overlay')
        && el.scrollHeight > el.clientHeight + 1
      const xScrollable = (ox === 'auto' || ox === 'scroll' || ox === 'overlay')
        && el.scrollWidth > el.clientWidth + 1

      return yScrollable || xScrollable
    }

    function isEditableTarget(el) {
      if (!(el instanceof Element))
        return false
      const tag = el.tagName
      if (tag === 'INPUT' || tag === 'TEXTAREA' || tag === 'SELECT')
        return true
      if (el.isContentEditable)
        return true
      return false
    }

    function isEditableFocused() {
      return isEditableTarget(doc.activeElement)
    }

    function pointerHasScrollableAncestor(target) {
      let el = target instanceof Element ? target : (target && target.parentElement)
      while (el && el !== doc.body && el !== doc.documentElement) {
        if (isEditableTarget(el) || isScrollableElement(el))
          return true
        el = el.parentElement
      }
      return false
    }

    function isOverlayOpen(options) {
      const except = (options && options.except) || []
      for (let i = 0; i < OVERLAY_SELECTORS.length; i++) {
        const selector = OVERLAY_SELECTORS[i]
        if (except.includes(selector))
          continue
        const nodes = doc.querySelectorAll(selector)
        for (let j = 0; j < nodes.length; j++) {
          if (isElementVisible(nodes[j]))
            return true
        }
      }
      return false
    }

    function isNonCatalogOverlayOpen() {
      return isOverlayOpen({ except: [CATALOG_SELECTOR] })
    }

    function isPaginatedHorizontalMode() {
      return !!doc.querySelector('.wr_horizontalReader')
    }

    function hasKeyModifier(event) {
      return event.ctrlKey || event.metaKey || event.altKey || event.shiftKey
    }

    function dispatchArrowKey(key) {
      const opts = { key, code: key, keyCode: key === 'ArrowRight' ? 39 : 37, which: key === 'ArrowRight' ? 39 : 37, bubbles: true, cancelable: true }
      doc.dispatchEvent(new KeyboardEvent('keydown', opts))
      doc.dispatchEvent(new KeyboardEvent('keyup', opts))
    }

    function turnPage(direction) {
      if (direction === 'next') {
        const next = doc.querySelector('button.renderTarget_pager_button.renderTarget_pager_button_right')
        if (next && isElementVisible(next)) {
          next.click()
          return
        }
        dispatchArrowKey('ArrowRight')
        return
      }

      const prev = doc.querySelector('button.renderTarget_pager_button:not(.renderTarget_pager_button_right)')
      if (prev && isElementVisible(prev)) {
        prev.click()
        return
      }
      dispatchArrowKey('ArrowLeft')
    }

    function findBookmarkControl() {
      const corner = doc.querySelector('.wr_reader_float_corner_bookmark_actionArea')
      if (corner)
        return corner

      return doc.querySelector(
        'li.readerCatalog_list_item.readerCatalog_list_item_selected div.readerCatalog_list_item_meta_add_bookMark',
      ) || doc.querySelector('div.readerCatalog_list_item_meta_add_bookMark')
    }

    /**
     * Prefer the page-corner ribbon (exists in CSS; often translateY(-100%) until hover),
     * then the catalog selected-row "+书签" control (may be in a display:none catalog).
     * Click whatever exists; leave success/failure to WeRead (e.g. logged-out toast).
     */
    function clickBookmarkControl() {
      const control = findBookmarkControl()
      if (!control)
        return false
      control.click()
      return true
    }

    function shouldHandleWheel(event) {
      if (!isPaginatedHorizontalMode())
        return false
      if (isOverlayOpen())
        return false
      if (pointerHasScrollableAncestor(event.target))
        return false
      return true
    }

    function onWheel(event) {
      if (!shouldHandleWheel(event)) {
        deltaCarry = 0
        return
      }

      // Reading surface is not a scroll container in horizontal mode; claim the wheel.
      event.preventDefault()

      const now = Date.now()
      if (now < cooldownUntil)
        return

      deltaCarry += event.deltaY
      if (Math.abs(deltaCarry) < WHEEL_THRESHOLD)
        return

      const direction = deltaCarry > 0 ? 'next' : 'prev'
      deltaCarry = 0
      cooldownUntil = now + COOLDOWN_MS
      turnPage(direction)
    }

    function blockNativePageKey(event) {
      event.preventDefault()
      event.stopPropagation()
    }

    function onKeyDown(event) {
      const key = event.key

      // ArrowLeft / ArrowRight: never re-click pager or re-dispatch (double-turn).
      // Block only when an overlay would let the book turn behind the panel.
      // Never preventDefault inside an editable (caret / selection).
      if (key === 'ArrowLeft' || key === 'ArrowRight') {
        if (isEditableFocused())
          return
        if (hasKeyModifier(event))
          return
        if (isOverlayOpen())
          blockNativePageKey(event)
        return
      }

      // ArrowDown → bookmark in horizontal mode; leave continuous scroll alone.
      if (key === 'ArrowDown') {
        if (!isPaginatedHorizontalMode())
          return
        if (isEditableFocused())
          return
        if (hasKeyModifier(event))
          return

        // Non-catalog overlays: block behind-the-panel paging, do not bookmark.
        if (isNonCatalogOverlayOpen()) {
          blockNativePageKey(event)
          return
        }

        // Remap only when a native bookmark control exists (flyleaf has none —
        // leave ArrowDown as native next-page there). Still block when catalog is
        // open with no control, so the book does not turn behind the panel.
        const bookmark = findBookmarkControl()
        if (bookmark) {
          blockNativePageKey(event)
          bookmark.click()
          return
        }
        if (isOverlayOpen())
          blockNativePageKey(event)
        return
      }

      // Letter shortcuts: ignore browser / IME chords.
      if (hasKeyModifier(event))
        return
      if (key.length !== 1)
        return
      if (isEditableFocused())
        return

      const letter = key.toLowerCase()

      if (letter === 'a' || letter === 'h') {
        if (!isPaginatedHorizontalMode())
          return
        if (isOverlayOpen())
          return
        event.preventDefault()
        turnPage('prev')
        return
      }

      if (letter === 'd' || letter === 'l') {
        if (!isPaginatedHorizontalMode())
          return
        if (isOverlayOpen())
          return
        event.preventDefault()
        turnPage('next')
        return
      }

      if (letter === 's' || letter === 'j') {
        // Allowed with catalog open; skip other overlays / missing controls (e.g. flyleaf).
        if (isNonCatalogOverlayOpen())
          return
        event.preventDefault()
        clickBookmarkControl()
      }
    }

    // Capture phase so we can stop ArrowDown / overlay ArrowLeft|Right before WeRead.
    doc.addEventListener('wheel', onWheel, { passive: false, capture: false })
    doc.addEventListener('keydown', onKeyDown, { capture: true })

    return function uninstallWereadPageTurner() {
      doc.removeEventListener('wheel', onWheel, { capture: false })
      doc.removeEventListener('keydown', onKeyDown, { capture: true })
    }
  }

  if (typeof globalThis !== 'undefined')
    globalThis.installWereadPageTurner = installWereadPageTurner
  else if (typeof window !== 'undefined')
    window.installWereadPageTurner = installWereadPageTurner

  installWereadPageTurner()
})()
